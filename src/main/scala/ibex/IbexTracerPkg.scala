object IbexTracerPkg {
  final case class InsnPattern(value: BigInt, mask: BigInt, width: Int) {
    def valueU: UInt = value.U(width.W)
    def maskU: UInt = mask.U(width.W)
    def matches(insn: BigInt): Boolean = (insn & mask) == (value & mask)
  }

  private final case class Field(value: BigInt, width: Int, care: Boolean)
  private def b(value: BigInt, width: Int): Field = Field(value, width, care = true)
  private def dc(width: Int): Field = Field(0, width, care = false)
  private def pat(width: Int, fields: Field*): InsnPattern = {
    require(fields.map(_.width).sum == width)
    var value = BigInt(0)
    var mask = BigInt(0)
    fields.foreach { field =>
      value = (value << field.width) | field.value
      mask = (mask << field.width) | (if (field.care) ((BigInt(1) << field.width) - 1) else BigInt(0))
    }
    InsnPattern(value, mask, width)
  }
  private def op(name: String): BigInt = IbexPkg.Opcode.encoding(name)
  private def opc(name: String): Field = b(op(name), 7)

